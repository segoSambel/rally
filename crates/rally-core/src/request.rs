use serde::{Deserialize, Serialize};

use crate::auth::Auth;
use crate::url::with_query;

#[derive(Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "UPPERCASE")]
pub enum Method {
    #[default]
    Get,
    Post,
    Put,
    Patch,
    Delete,
}

impl Method {
    pub const ALL: [Method; 5] = [
        Method::Get,
        Method::Post,
        Method::Put,
        Method::Patch,
        Method::Delete,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            Method::Get => "GET",
            Method::Post => "POST",
            Method::Put => "PUT",
            Method::Patch => "PATCH",
            Method::Delete => "DELETE",
        }
    }
}

pub struct ApiRequest {
    pub method: Method,
    pub url: String,
    pub headers: Vec<(String, String)>,
    pub body: String,
}

impl ApiRequest {
    /// Assembles a request from the editor contents.
    ///
    /// `params` and any query parameter from `auth` are appended to `url`. Headers set
    /// explicitly win over the ones generated by the auth scheme.
    pub fn build(
        method: Method,
        url: &str,
        mut params: Vec<(String, String)>,
        mut headers: Vec<(String, String)>,
        auth: &Auth,
        body: String,
    ) -> Self {
        let auth = auth.parts();
        params.extend(auth.query);
        for (name, value) in auth.headers {
            if !headers
                .iter()
                .any(|(existing, _)| existing.eq_ignore_ascii_case(&name))
            {
                headers.push((name, value));
            }
        }

        Self {
            method,
            url: with_query(url, &params),
            headers,
            body,
        }
    }
}
